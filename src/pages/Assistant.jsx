import { useEffect, useRef, useState } from 'react';
import ReactMarkdown from 'react-markdown';
import { Link } from 'react-router-dom';
import { assistantApi, referralApi } from '../api/services';
import { useAuth } from '../context/AuthContext';
import { useApp } from '../context/AppContext';
import { useAction, useFetch } from '../hooks';
import { PageHeader } from '../components/ui/data';
import { Alert, Badge, Card, Freshness, StatusBadge, UrgencyBadge } from '../components/ui/display';
import { Button, Select } from '../components/ui/forms';
import Icon from '../components/ui/Icon';
import { fmtTime } from '../utils/format';

function Cards({ list }) {
  if (!list?.length) return null;
  return (
    <div className="grid cols-2" style={{ marginTop: 10 }}>
      {list.map((h) => (
        <div key={h.id} className="hosp-mini">
          <div className="row between"><Link to={`/app/hospitals/${h.id}`} style={{ fontWeight: 650 }}>{h.name}</Link>{h.score != null && <Badge tone="teal">{h.score}%</Badge>}</div>
          <span className="xs muted">{h.city}</span>
          {h.highlights?.slice(0, 4).map((x, i) => <span key={i} className="xs">{x}</span>)}
          <Freshness updatedAt={h.resourcesUpdatedAt} stale={h.resourcesStale} compact />
        </div>
      ))}
    </div>
  );
}

export default function Assistant() {
  const { user } = useAuth();
  const { status } = useApp();
  const prompts = useFetch(() => assistantApi.prompts(), []);
  const refs = useFetch(() => referralApi.list({ sort: 'updatedAt', size: 30 }), []);
  const [msgs, setMsgs] = useState([]);
  const [text, setText] = useState('');
  const [refId, setRefId] = useState('');
  const [mode, setMode] = useState(status.data?.assistantMode || 'OFFLINE');
  const [busy, run] = useAction();
  const end = useRef(null);
  const sel = refs.data?.content.find((r) => String(r.id) === refId);
  useEffect(() => { if (status.data?.assistantMode) setMode(status.data.assistantMode); }, [status.data]);
  useEffect(() => { end.current?.scrollIntoView({ block: 'nearest' }); }, [msgs.length, busy]);

  const ask = (q) => {
    const message = (q ?? text).trim();
    if (!message) return;
    const history = msgs.slice(-6).map((m) => ({ role: m.role, content: m.content }));
    setMsgs((l) => [...l, { role: 'user', content: message, at: new Date().toISOString() }]); setText('');
    run(async () => {
      try {
        const r = await assistantApi.chat({ message, referralId: refId ? Number(refId) : null, history });
        setMode(r.mode); setMsgs((l) => [...l, { role: 'assistant', content: r.answer, cards: r.hospitals, notes: r.dataNotes, sources: r.sources, at: r.generatedAt }]);
      } catch (e) { setMsgs((l) => [...l, { role: 'assistant', error: true, content: e.message, at: new Date().toISOString() }]); }
    });
  };

  return (
    <>
      <PageHeader title="AI coordination assistant" description="Ask about the referral workflow or what current application data shows. Answers are grounded in application data and documentation."
        crumbs={[{ label: 'Dashboard', to: '/app' }, { label: 'Coordination assistant' }]} actions={<Badge tone={mode === 'LIVE' ? 'success' : 'warning'} icon="Sparkles">{mode === 'LIVE' ? 'Live model' : 'Not connected'}</Badge>} />
      <div className="assistant">
        <Card className="chat-pane" as="section" aria-label="Conversation">
          <div className="chat-scroll" role="log" aria-live="polite">
            {msgs.length === 0 && (
              <div className="stack">
                <Alert tone={mode === 'LIVE' ? 'info' : 'warning'} title={mode === 'LIVE' ? 'Language model connected' : 'Not connected'}>
                  {mode === 'LIVE' ? 'Answers are written by a language model using only retrieved application data.' : 'No language-model key is configured, so answers are generated by deterministic retrieval rules from the same data. Nothing is sent to an external service.'}
                  {' '}The assistant is not a clinician and never makes clinical or acceptance decisions.
                </Alert>
                <div><div className="field-label" style={{ marginBottom: 8 }}>Suggested questions</div>
                  <div className="view-chips">{(prompts.data || []).map((p) => <button key={p.label} className="chip" disabled={p.needsReferral && !refId} title={p.needsReferral && !refId ? 'Select a referral on the right first' : undefined} onClick={() => ask(p.prompt)}>{p.label}</button>)}</div></div>
              </div>
            )}
            {msgs.map((m, i) => (
              <div key={i} className={`bubble ${m.role === 'user' ? 'user' : 'bot'}`}>
                {m.role === 'user' ? m.content : m.error ? <span style={{ color: 'var(--danger)' }}>{m.content}</span> : <div className="md"><ReactMarkdown>{m.content}</ReactMarkdown></div>}
                {m.cards && <Cards list={m.cards} />}
                {m.notes?.map((n, k) => <div key={k} className="xs" style={{ marginTop: 8 }}><Icon name="TriangleAlert" size={12} /> {n}</div>)}
                {m.sources?.length > 0 && <div className="xs muted" style={{ marginTop: 8 }}>Sources: {m.sources.join(' · ')}</div>}
                <div className="xs" style={{ marginTop: 6, opacity: 0.7 }}>{m.role === 'user' ? 'You' : 'Assistant'} · {fmtTime(m.at)}</div>
              </div>
            ))}
            {busy && <div className="bubble bot" role="status" aria-label="Assistant is preparing an answer"><span className="typing"><i /><i /><i /></span></div>}
            <div ref={end} />
          </div>
          <form className="compose" onSubmit={(e) => { e.preventDefault(); ask(); }}>
            <label htmlFor="ask" className="sr-only">Ask the coordination assistant</label>
            <input id="ask" className="input" value={text} maxLength={1000} onChange={(e) => setText(e.target.value)} placeholder="e.g. Which hospitals list Cardiology and have an ICU bed available?" />
            <Button type="submit" icon="Send" loading={busy}>Ask</Button>
          </form>
        </Card>
        <div className="stack">
          <Card title="Context">
            <div className="stack">
              <Select label="Referral in context" value={refId} onChange={(e) => setRefId(e.target.value)} placeholder="None (general questions)" options={(refs.data?.content || []).map((r) => [r.id, `${r.referralCode} · ${r.emergencyCondition}`.slice(0, 60)])} help={user.role === 'RECEIVING_HOSPITAL' ? 'Context lets the assistant summarise requirements.' : 'Context lets the assistant explain match results.'} />
              {sel && <div className="hosp-mini"><div className="row between"><strong>{sel.referralCode}</strong><StatusBadge status={sel.status} /></div><UrgencyBadge urgency={sel.urgency} /><span className="small">{sel.requiredSpecialty}</span><Link to={`/app/referrals/${sel.id}`} className="small">Open referral</Link></div>}
            </div>
          </Card>
          <Card title="Good to know" className="tint"><ul className="small" style={{ margin: 0, paddingLeft: 18, display: 'grid', gap: 6 }}>
            <li>Answers use current application data and flag stale information.</li><li>It cannot diagnose, prescribe or recommend treatment.</li><li>Your referral access rules apply to what it can see.</li><li>Read <Link to="/app/help">Help</Link> for how scoring works.</li></ul></Card>
        </div>
      </div>
    </>
  );
}
